extern void printk(const char *fmt, ...);

/* Embedded sample_mod.ko binary data generated by SCons */
#include "sample_mod_ko.h"

static int test_kmod_core_and_syms(void)
{
    /* Test manual export and lookup */
    static int s_dummy_var = 42;
    if (cherry_kmod_export_symbol("s_dummy_var", (uintptr_t)&s_dummy_var) != 0) {
        return -1;
    }
    uintptr_t a = cherry_kmod_lookup_symbol("s_dummy_var");
    if (a != (uintptr_t)&s_dummy_var) {
        return -2;
    }
    if (cherry_kmod_unexport_symbol("s_dummy_var") != 0) {
        return -3;
    }
    if (cherry_kmod_lookup_symbol("s_dummy_var") != 0) {
        return -4;
    }
    return 0;
}

static int test_kmod_buffer_execution(void)
{
    struct cherry_kmod *mod = cherry_kmod_load_buffer(g_sample_mod_ko, g_sample_mod_ko_len, "sample_buf");
    if (!mod) {
        printk("kmod_test: cherry_kmod_load_buffer failed\n");
        return -1;
    }

    if (mod->state != KMOD_STATE_LIVE) {
        return -2;
    }

    /* Look up sample_calc from module */
    uintptr_t calc_addr = cherry_kmod_lookup_symbol("sample_calc");
    if (!calc_addr) {
        printk("kmod_test: sample_calc not found in symbol table\n");
        cherry_kmod_unload("sample_buf");
        return -3;
    }

    typedef int (*calc_fn_t)(int, int);
    calc_fn_t fn = (calc_fn_t)calc_addr;
    int res = fn(5, 7);
    /* In sample_mod: a * 10 + b + g_sample_counter = 50 + 7 + 500 = 557 */
    if (res != 557) {
        printk("kmod_test: sample_calc(5, 7) returned %d, expected 557\n", res);
        cherry_kmod_unload("sample_buf");
        return -4;
    }

    /* Look up sample_get_tag */
    uintptr_t tag_addr = cherry_kmod_lookup_symbol("sample_get_tag");
    if (!tag_addr) {
        cherry_kmod_unload("sample_buf");
        return -5;
    }
    typedef const char *(*tag_fn_t)(void);
    tag_fn_t tag_fn = (tag_fn_t)tag_addr;
    const char *tag_str = tag_fn();
    if (!tag_str || strcmp(tag_str, "CHERRY_SAMPLE_TAG_OK") != 0) {
        cherry_kmod_unload("sample_buf");
        return -6;
    }

    /* Check lsmod output */
    char ls_buf[512];
    int len = cherry_kmod_list(ls_buf, sizeof(ls_buf));
    if (len <= 0 || strstr(ls_buf, "sample_buf") == NULL) {
        cherry_kmod_unload("sample_buf");
        return -7;
    }

    /* Unload module */
    if (cherry_kmod_unload("sample_buf") != 0) {
        return -8;
    }

    /* Verify symbols cleaned up */
    if (cherry_kmod_lookup_symbol("sample_calc") != 0) {
        return -9;
    }

    return 0;
}

static int test_kmod_vfs_and_shell(void)
{
    /* Write sample_mod.ko into VFS (/etc/sample_mod.ko) */
    int fd = open("/etc/sample_mod.ko", O_WRONLY | O_CREAT | O_TRUNC, 0644);
    if (fd < 0) {
        printk("kmod_test: cannot create /etc/sample_mod.ko (err=%d)\n", fd);
        return -1;
    }
    ssize_t wr = write(fd, g_sample_mod_ko, g_sample_mod_ko_len);
    close(fd);

    if (wr != (ssize_t)g_sample_mod_ko_len) {
        printk("kmod_test: write failed\n");
        return -2;
    }

    /* 1. Test shell insmod command */
    char *ins_argv[] = {"insmod", "/etc/sample_mod.ko", NULL};
    if (cherry_kmod_cmd_insmod(2, ins_argv) != 0) {
        printk("kmod_test: insmod failed\n");
        return -3;
    }

    /* Verify loaded */
    struct cherry_kmod *mod = cherry_kmod_find("sample_mod");
    if (!mod) {
        return -4;
    }

    /* 2. Test shell lsmod command */
    char *ls_argv[] = {"lsmod", NULL};
    if (cherry_kmod_cmd_lsmod(1, ls_argv) != 0) {
        return -5;
    }

    /* 3. Call function in loaded module */
    uintptr_t calc_addr = cherry_kmod_lookup_symbol("sample_calc");
    if (!calc_addr) {
        return -6;
    }
    typedef int (*calc_fn_t)(int, int);
    int res = ((calc_fn_t)calc_addr)(10, 2);
    if (res != 602) { /* 100 + 2 + 500 = 602 */
        return -7;
    }

    /* 4. Test shell rmmod command */
    char *rm_argv[] = {"rmmod", "sample_mod", NULL};
    if (cherry_kmod_cmd_rmmod(2, rm_argv) != 0) {
        return -8;
    }

    if (cherry_kmod_find("sample_mod") != NULL) {
        return -9;
    }

    return 0;
}

int cherry_kmod_run_tests(void)
{
    printk("[kmod] ==> starting cherrykmod acceptance test suite...\n");

    int r1 = cherry_kmod_init();
    int r2 = test_kmod_core_and_syms();
    int r3 = test_kmod_buffer_execution();
    int r4 = test_kmod_vfs_and_shell();

    bool pass = (r1 == 0) && (r2 == 0) && (r3 == 0) && (r4 == 0);

    printk("[kmod] [kmod-verify] init=%s syms=%s load_buf=%s exec_func=%s vfs_file=%s shell_cmds=%s unload=%s all=%s\n",
           r1 == 0 ? "pass" : "fail",
           r2 == 0 ? "pass" : "fail",
           r3 == 0 ? "pass" : "fail",
           r3 == 0 ? "pass" : "fail",
           r4 == 0 ? "pass" : "fail",
           r4 == 0 ? "pass" : "fail",
           (r3 == 0 && r4 == 0) ? "pass" : "fail",
           pass ? "pass" : "fail");

    return pass ? 0 : -1;
}
